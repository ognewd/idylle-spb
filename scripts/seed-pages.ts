async function seedPages() {
  try {
    console.log('Начинаю создание страниц...\n');

    for (const pageData of defaultPages) {
      const existing = await prisma.page.findUnique({
        where: { slug: pageData.slug },
      });

      if (existing) {
        console.log(`✓ Страница "${pageData.title}" (${pageData.slug}) уже существует, пропускаю`);
      } else {
        await prisma.page.create({
          data: pageData,
        });
        console.log(`✓ Создана страница "${pageData.title}" (${pageData.slug})`);
      }
    }

    console.log('\n✅ Все страницы созданы!');
  } catch (error) {
    console.error('❌ Ошибка при создании страниц:', error);
    throw error;
  } finally {
    await prisma.$disconnect();
  }
}

seedPages();

